/* =============================================================================
 * ClassSync — Section Office / Coordinator routine builder + PDF export
 * =============================================================================
 * Adds the "Section Office" role (and gives Coordinator/Admin the same tool).
 * The existing "Add routine" screen is the routine builder; this layer adds a
 * "Download routine PDF" button that exports every batch in the selected
 * semester as real tables in a valid PDF, generated in-browser with no library.
 *
 * Load after er-features.js. No existing file behaviour is overwritten.
 * ============================================================================= */
(function(){
  'use strict';

  /* ---------------- role wiring ---------------- */
  try {
    if (typeof ROLETABS !== 'undefined' && typeof ROLEN !== 'undefined'){
      ROLEN.office = 'Section Office';
      ROLETABS.office = ['add','find'];
      // CR login removed: it is no longer offered on the home page or login screen.
      delete ROLEN.cr;
      delete ROLETABS.cr;
      // Coordinators and admins can also build/export the routine.
      if (ROLETABS.coord && ROLETABS.coord.indexOf('add') < 0) ROLETABS.coord.push('add');
    }
  } catch(e){ /* roles unavailable — feature still loads on login screens */ }

  // The home page was drawn before this script loaded; refresh it so the new
  // "Try as section office" demo button appears.
  setTimeout(function(){
    try {
      // A real Supabase session sets __csLiveUser. If it is absent, any U found
      // came from the old demo login stored in localStorage — clear it so the
      // app always starts on the login/home screen for fresh login testing.
      if (!window.__csLiveUser){
        try { localStorage.removeItem('cs_user'); } catch(e){}
        if (typeof U !== 'undefined') U = null;
        if (typeof page !== 'undefined') page = 'home';
        if (typeof draw === 'function') draw();
      }
    } catch(e){}
  }, 60);

  /* ---------------- tiny PDF writer (ASCII, Type1 Helvetica) ---------------- */
  function ascii(s){
    return String(s == null ? '' : s)
      .replace(/[\u2013\u2014]/g,'-').replace(/[\u2018\u2019]/g,"'")
      .replace(/[^\x20-\x7E]/g,'?');
  }
  function pdfEsc(s){ return ascii(s).replace(/\\/g,'\\\\').replace(/\(/g,'\\(').replace(/\)/g,'\\)'); }
  function T(x,y,s,size){ return 'BT /F1 '+(size||9)+' Tf '+x+' '+y+' Td ('+pdfEsc(s)+') Tj ET\n'; }
  function L(x1,y1,x2,y2){ return x1+' '+y1+' m '+x2+' '+y2+' l S\n'; }

  /* Draw a bordered table. Returns the next free Y coordinate. */
  function table(c, x, y, widths, headers, rows){
    var total = widths.reduce(function(a,b){ return a+b; },0);
    var rowH = 15, headH = 19;
    c += '0.6 w\n';
    c += L(x,y,x+total,y);
    var cx = x;
    headers.forEach(function(h,i){ c += T(cx+4, y-13, h, 9); cx += widths[i]; });
    y -= headH;
    c += L(x,y,x+total,y);
    var xx;
    rows.forEach(function(row){
      var cy = y - rowH;
      c += L(x,y,x,cy) + L(x+total,y,x+total,cy);
      xx = x;
      widths.forEach(function(w,i){
        c += T(xx+4, cy-10, row[i] == null ? '' : row[i], 8.5);
        xx += w;
      });
      xx = x;
      widths.forEach(function(w){ c += L(xx,y,xx,cy); xx += w; });
      c += L(x,cy,x+total,cy);
      y = cy;
    });
    return { content: c, y: y };
  }

  function makePDF(title, tables){
    var pages = [];
    var content = T(42, 800, title, 17) + T(42, 783, 'Generated by ClasSync - Section Office', 9) + '\n';
    var y = 760;
    tables.forEach(function(tb){
      if (y < 150){
        pages.push(content);
        content = T(42, 800, title + ' (continued)', 13) + '\n';
        y = 770;
      }
      content += T(42, y, tb.title, 11) + '\n';
      var res = table(content, 42, y-6, tb.widths, tb.headers, tb.rows);
      content = res.content;
      y = res.y;
    });
    pages.push(content);

    var objs = [];
    var n = pages.length;
    objs[1] = '<< /Type /Catalog /Pages 2 0 R >>';
    var kids = [];
    for (var i=0;i<n;i++) kids.push((4+i)+' 0 R');
    objs[2] = '<< /Type /Pages /Kids ['+kids.join(' ')+'] /Count '+n+' >>';
    objs[3] = '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>';
    for (var p=0;p<n;p++){
      objs[4+p] = '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] '+
        '/Resources << /Font << /F1 3 0 R >> >> /Contents '+(4+n+p)+' 0 R >>';
    }
    for (var q=0;q<n;q++){
      var stream = pages[q];
      objs[4+n+q] = '<< /Length '+stream.length+' >>\nstream\n'+stream+'endstream';
    }

    var pdf = '%PDF-1.4\n';
    var offsets = [];
    for (var k=1;k<objs.length;k++){
      offsets[k] = pdf.length;
      pdf += k+' 0 obj\n'+objs[k]+'\nendobj\n';
    }
    var xref = pdf.length;
    pdf += 'xref\n0 '+objs.length+'\n0000000000 65535 f \n';
    for (var m=1;m<objs.length;m++){
      pdf += ('0000000000'+offsets[m]).slice(-10)+' 00000 n \n';
    }
    pdf += 'trailer\n<< /Size '+objs.length+' /Root 1 0 R >>\nstartxref\n'+xref+'\n%%EOF';
    return pdf;
  }

  /* ---------------- data + download ---------------- */
  function routineTables(){
    var sem = (typeof sem !== 'undefined' && sem) ? sem : (window.CLASSSYNC_CONFIG || {}).semester || 'Fall 2026';
    var data = (typeof R === 'function') ? R() : {};
    var out = [];
    Object.keys(data).sort().forEach(function(batch){
      var rows = (data[batch] || []).slice().sort(function(a,b){ return a[0]-b[0] || a[1]-b[1]; });
      if (!rows.length) return;
      var tableRows = rows.map(function(r){
        var d = ['Mon','Tue','Wed','Thu'][r[0]] || ('D'+r[0]);
        var p = 'P'+(r[1]+1);
        var tm = (typeof PT !== 'undefined' && PT[r[1]]) ? PT[r[1]][0] : '';
        return [d, p+' ('+tm+')', r[3], r[4], r[5], r[2] + (r[2]>1?' periods':' period')];
      });
      out.push({
        title: 'Batch ' + batch + ' - ' + sem,
        widths: [55, 105, 115, 65, 70, 90],
        headers: ['Day','Period','Course','Teacher','Room','Length'],
        rows: tableRows
      });
    });
    if (!out.length){
      out.push({ title:'No routine data for '+sem, widths:[500], headers:['Message'], rows:[['Add classes in the Add routine screen first.']] });
    }
    return { sem: sem, tables: out };
  }

  function downloadPDF(){
    try {
      var info = routineTables();
      var blob = new Blob([makePDF('ClassSync Routine - '+info.sem, info.tables)], {type:'application/pdf'});
      var a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = 'ClassSync-Routine-' + info.sem.replace(/\s+/g,'-') + '.pdf';
      document.body.appendChild(a);
      a.click();
      setTimeout(function(){ URL.revokeObjectURL(a.href); a.remove(); }, 1000);
      if (typeof toast === 'function') toast('Routine PDF downloaded.');
    } catch(e){
      if (typeof toast === 'function') toast('Could not create PDF: ' + e.message);
      else alert('Could not create PDF: ' + e.message);
    }
  }

  /* ---------------- add the button to the routine builder ---------------- */
  function install(){
    if (typeof window.vAdd !== 'function'){ setTimeout(install, 250); return; }
    var original = window.vAdd;
    window.vAdd = function(){
      original();
      var view = document.getElementById('view'); if (!view) return;
      if (document.getElementById('soPdf')) return;
      var bar = document.createElement('div');
      bar.className = 'card';
      bar.style.marginBottom = '12px';
      bar.innerHTML = '<div class="row" style="justify-content:space-between"><div>' +
        '<h3 class="h3" style="margin:0">Section Office - routine PDF</h3>' +
        '<p class="sub" style="margin-top:4px">Build the routine below, then export every batch of this semester as a table in a PDF.</p></div>' +
        '<button class="b gold" id="soPdf">Download routine PDF</button></div>';
      view.insertBefore(bar, view.firstChild);
      document.getElementById('soPdf').onclick = downloadPDF;
    };
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', install);
  else install();

  window.SECTION_OFFICE = { download: downloadPDF };
})();
